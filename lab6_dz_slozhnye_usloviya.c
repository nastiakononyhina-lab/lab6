#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

// Домашнее задание "сложные условия", вариант 11.
// Проверить, принадлежит ли точка (x, y) закрашенной области.
//
// Область (справа от оси y, то есть x >= 0):
//   выше оси x (y >= 0)  - внутри круга радиуса 3: x*x + y*y <= 9
//   ниже оси x (y <= 0)  - внутри круга радиуса 4: x*x + y*y <= 16
//
// КОНТРОЛЬНЫЕ ПРИМЕРЫ:
// (1; 1)    -> 1 + 1 = 2 <= 9            -> принадлежит
// (2.5; 2)  -> 6.25 + 4 = 10.25 > 9      -> не принадлежит (сверху)
// (3.5; -1) -> 12.25 + 1 = 13.25 <= 16   -> принадлежит (снизу)
// (-1; 1)   -> x < 0                      -> не принадлежит

int main()
{
    setlocale(LC_ALL, "Russian");

    float x, y;
    float r2;   // квадрат расстояния от начала координат

    printf("Введите x: ");
    scanf("%f", &x);
    printf("Введите y: ");
    scanf("%f", &y);

    r2 = x * x + y * y;

    if ((x >= 0 && y >= 0 && r2 <= 9) || (x >= 0 && y <= 0 && r2 <= 16))
        printf("Точка принадлежит области\n");
    else
        printf("Точка не принадлежит области\n");

    return 0;
}
